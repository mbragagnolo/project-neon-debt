def _mirror(tile):
    return [row[::-1] for row in tile]


def _vflip(tile):
    return list(reversed(tile))


def _hcat(*tiles):
    return ["".join(rows) for rows in zip(*tiles)]


def _vcat(*tiles):
    out = []
    for t in tiles:
        out.extend(t)
    return out


