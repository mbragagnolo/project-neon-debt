"""Props: everything the player walks up to, and the dressing around it.

Grids are art pixels at PLAY (2 texture px each, bible/art.json), so one
character here is the same size on screen as one pixel of a character sheet.
They used to be saved at 3, which is what the art-director's first review
found: a crate's pixel half again the size of the pixel of the woman
standing on it (art/reviews/2026-09-16/).

`o` is still the outline colour, but only inside a shape -- a hole, a seam,
a screen's frame. Every `o` that touches air is rewritten by `edge()` into a
step of the colour it sits against, which is the shading bar's rule: an edge
is the darker step of the local colour, and the lit edge (the step above the
face) sits on the light side only. That used to be done by hand and so was
not done at all: 19 props carried a flat black ring round the whole
silhouette.
"""
