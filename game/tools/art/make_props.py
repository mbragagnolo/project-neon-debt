# --- The ramps, for the edge pass ----------------------------------------------------
# Each is one material dark -> light. A step's neighbours are what an edge is
# drawn with, so this is the shading bar written as data.

RAMPS = [
    ["void", "bg0", "bg1", "bg2", "bg3"],
    ["steel0", "steel1", "steel2", "steel3", "steel4"],
    ["concrete0", "concrete1", "concrete2", "concrete3"],
    ["rust0", "rust1", "rust2", "rust3"],
    ["olive_d", "olive", "olive_l", "olive_ll"],
    ["amber_d", "amber", "amber_l"],
    ["cyan_d", "cyan", "cyan_l"],
    ["magenta_d", "magenta", "magenta_l"],
    ["red_d", "red", "red_l"],
    ["violet_d", "violet"],
    ["green_d", "green"],
    ["grey_d", "grey", "white"],
    ["chrome_d", "chrome"],
    ["black", "black_l"],
    ["sodium", "warm"],
]
_STEP_OF = {name: (i, j) for i, ramp in enumerate(RAMPS) for j, name in enumerate(ramp)}


def _neighbour_step(name, lighter):
    """The step above or below `name` in its ramp; `name` itself at the end."""
    at = _STEP_OF.get(name)
    if at is None:
        return name
    i, j = at
    ramp = RAMPS[i]
    j2 = min(j + 1, len(ramp) - 1) if lighter else max(j - 1, 0)
    return ramp[j2]


_CHAR_OF = {}
for _k, _v in L.items():
    _CHAR_OF.setdefault(_v, _k)

AIR = {".", " "}


def edge(rows, light="ul"):
    """Draw the silhouette's edge from the shape, instead of typing it.

    Every cell that touches air becomes a step of its own colour: the step
    above it where the light hits (the top and the left, unless the room says
    otherwise), the step below it everywhere else. That is the shading bar's
    rule, and having it here rather than in the grids is why it is now
    actually obeyed -- typed by hand it was skipped, and nineteen props
    carried a flat black ring round the whole silhouette instead.

    A grid therefore carries shape and material only. `o` still means the
    outline colour and is left alone: inside a shape it is a hole, a seam or
    a screen's frame, all of which are meant to be dark.
    """
    h = len(rows)
    w = max(len(r) for r in rows)
    g = [list(r.ljust(w, ".")[:w]) for r in rows]
    up, left = "u" in light, "l" in light

    def at(x, y):
        return g[y][x] if 0 <= x < w and 0 <= y < h else "."

    out = [row[:] for row in g]
    for y in range(h):
        for x in range(w):
            c = g[y][x]
            if c in AIR or c == "o" or c not in L:
                continue
            around = ((0, -1), (0, 1), (-1, 0), (1, 0))
            if not any(at(x + dx, y + dy) in AIR for dx, dy in around):
                continue                       # interior
            lit = ((at(x, y - 1) in AIR) if up else (at(x, y + 1) in AIR)) or \
                  ((at(x - 1, y) in AIR) if left else (at(x + 1, y) in AIR))
            want = _neighbour_step(L[c], lighter=lit)
            out[y][x] = _CHAR_OF.get(want, c)
    return ["".join(row) for row in out]


def emit(name, rows, sub="props", light="ul"):
    img = draw(edge(rows, light), L)
    save(img, "%s/%s.png" % (sub, name), scale=PLAY)
    return img


